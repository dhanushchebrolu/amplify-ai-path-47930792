/** Card blurb for a sub-category, with a generic fallback for new entries. */
export function subDescription(catSlug: string, subSlug: string, subName: string): string {
  return SUB_DESCRIPTIONS[`${catSlug}/${subSlug}`]
    ?? `Explore the best ${subName.replace(/^AI\s+/i, "AI ").toLowerCase().replace(/^ai /, "AI ")} in one place.`;
}

